package main

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// Only schemas opting in with x-typescript are emitted. Unsupported shapes
// fail generation instead of silently weakening the client contract.
func renderModels(document map[string]any) (string, error) {
	components, _ := document["components"].(map[string]any)
	schemas, _ := components["schemas"].(map[string]any)
	names := make([]string, 0)
	for name, raw := range schemas {
		schema, _ := raw.(map[string]any)
		if schema["x-typescript"] == true {
			names = append(names, name)
		}
	}
	sort.Strings(names)
	var result strings.Builder
	result.WriteString("// Code generated by tools/codegen; DO NOT EDIT.\n\n")
	for _, name := range names {
		value, err := modelType(schemas[name], schemas)
		if err != nil {
			return "", fmt.Errorf("schema %s: %w", name, err)
		}
		result.WriteString("export type " + name + " = " + value + ";\n\n")
	}
	return result.String(), nil
}

func modelType(raw any, schemas map[string]any) (string, error) {
	schema, ok := raw.(map[string]any)
	if !ok {
		return "", fmt.Errorf("schema must be an object")
	}
	if ref, ok := schema["$ref"].(string); ok {
		const prefix = "#/components/schemas/"
		name := strings.TrimPrefix(ref, prefix)
		target, _ := schemas[name].(map[string]any)
		if !strings.HasPrefix(ref, prefix) || target["x-typescript"] != true {
			return "", fmt.Errorf("reference %s is not an emitted schema", ref)
		}
		return name, nil
	}
	switch schema["type"] {
	case "string":
		return "string", nil
	case "integer", "number":
		return "number", nil
	case "boolean":
		return "boolean", nil
	case "array":
		item, err := modelType(schema["items"], schemas)
		return "Array<" + item + ">", err
	case "object":
		properties, _ := schema["properties"].(map[string]any)
		if len(properties) == 0 {
			return "Record<string, unknown>", nil
		}
		if schema["additionalProperties"] != false {
			return "", fmt.Errorf("typed objects must disallow additional properties")
		}
		required := map[string]bool{}
		if fields, ok := schema["required"].([]any); ok {
			for _, field := range fields {
				required[fmt.Sprint(field)] = true
			}
		}
		names := make([]string, 0, len(properties))
		for name := range properties {
			names = append(names, name)
		}
		sort.Strings(names)
		var fields []string
		for _, name := range names {
			value, err := modelType(properties[name], schemas)
			if err != nil {
				return "", err
			}
			optional := "?"
			if required[name] {
				optional = ""
			}
			fields = append(fields, strconv.Quote(name)+optional+": "+value+";")
		}
		return "{ " + strings.Join(fields, " ") + " }", nil
	default:
		return "", fmt.Errorf("unsupported schema type %v", schema["type"])
	}
}
